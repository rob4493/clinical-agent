"""Generate typed representations; check mode never writes or refreshes evidence pins."""

import argparse
import hashlib
import json
from pathlib import Path

Root = Path(__file__).resolve().parents[1]
SchemaPath = Root / "shared/clinicalData.schema.json"


def checkVocabulary(schema):
    supported = {"$schema", "$id", "$ref", "$defs", "title", "description", "type", "properties", "required", "additionalProperties", "anyOf", "enum", "const", "default", "minimum", "maximum", "minLength", "maxLength", "pattern", "items", "minItems", "maxItems", "uniqueItems", "x-uniqueId", "x-stateValue", "x-clinicalDate", "x-sourceSpan", "x-intent", "x-caseIntegrity"}
    def visit(definition):
        if set(definition) - supported or definition.get("type") == "object" and definition.get("additionalProperties") is not False:
            raise ValueError("Unsupported clinical schema vocabulary.")
        if "$ref" in definition and (not definition["$ref"].startswith("#/$defs/") or definition["$ref"].split("/")[-1] not in schema["$defs"]):
            raise ValueError("Unsupported clinical schema reference.")
        for group in ("properties", "$defs"):
            for nested in definition.get(group, {}).values():
                visit(nested)
        for option in definition.get("anyOf", []):
            visit(option)
        if "items" in definition:
            visit(definition["items"])
    visit(schema)


def generate():
    source = SchemaPath.read_bytes()
    schema = json.loads(source)
    checkVocabulary(schema)
    digest = hashlib.sha256(source).hexdigest()
    ts = ["// Generated by tools/schemaSync.py; edit the canonical JSON, not this file.", f"export const SchemaHash = '{digest}';"]
    py = ['"""Generated schema representations; do not edit independently."""', "from __future__ import annotations", "from typing import ClassVar, Literal", "from pydantic import BaseModel, ConfigDict, Field, model_validator", "from backend.app.models.schemaRules import Schema, validateNode", f'SchemaHash = "{digest}"',
        'class ClinicalModel(BaseModel):', '    """Transient, bounded records; repr excludes every submitted field."""', '    model_config = ConfigDict(extra="forbid", strict=True, hide_input_in_errors=True, allow_inf_nan=False, regex_engine="python-re")', '    schemaName: ClassVar[str]', '    @model_validator(mode="before")', '    @classmethod', '    def checkSchema(cls, record):', '        if isinstance(record, BaseModel):', '            record = record.model_dump(mode="json", exclude_unset=True)', '        validateNode(record, Schema if cls.schemaName == "CanonicalCase" else Schema["$defs"][cls.schemaName])', '        return record']
    def expression(definition, language):
        if "$ref" in definition:
            return definition["$ref"].split("/")[-1]
        if "anyOf" in definition:
            return " | ".join(expression(option, language) for option in definition["anyOf"])
        if "enum" in definition or "const" in definition:
            entries = definition.get("enum", [definition.get("const")])
            return " | ".join(json.dumps(entry) for entry in entries) if language == "ts" else "Literal[" + ", ".join(repr(entry) for entry in entries) + "]"
        kind = definition["type"]
        if kind == "array":
            inner = expression(definition["items"], language)
            return f"Array<{inner}>" if language == "ts" else f"list[{inner}]"
        return {"ts": {"string": "string", "number": "number", "integer": "number", "boolean": "boolean", "null": "null"}, "py": {"string": "str", "number": "float", "integer": "int", "boolean": "bool", "null": "None"}}[language][kind]
    definitions = {**schema["$defs"], "CanonicalCase": schema}
    for name, definition in definitions.items():
        if definition.get("type") != "object":
            ts.append(f"export type {name} = {expression(definition, 'ts')};")
            py.append(f"{name} = {expression(definition, 'py')}")
            continue
        ts.append(f"export interface {name} {{")
        py.extend([f"class {name}(ClinicalModel):", f'    schemaName: ClassVar[str] = "{name}"'])
        extensions = {key: entry for key, entry in definition.items() if key.startswith("x-")}
        if extensions:
            py.append(f"    model_config = ConfigDict(json_schema_extra={extensions!r})")
        for fieldName, field in definition["properties"].items():
            required = fieldName in definition.get("required", [])
            ts.append(f"  {fieldName}{'' if required else '?'}: {expression(field, 'ts')};")
            annotation = expression(field, "py")
            # Runtime JSON-schema validation enforces conditional/date/reference
            # constraints too; the generator does not invent semantic defaults.
            numeric = ", strict=False" if field.get("type") == "integer" else ""
            bounds = schema["$defs"].get(field.get("$ref", "").split("/")[-1], field)
            for key, argument in {"minLength": "min_length", "maxLength": "max_length", "pattern": "pattern", "minItems": "min_length", "maxItems": "max_length", "minimum": "ge", "maximum": "le"}.items():
                if key in bounds:
                    numeric += f", {argument}={bounds[key]!r}"
            default = '...' if required else 'default=' + repr(field.get('default'))
            py.append(f"    {fieldName}: {annotation} = Field({default}, repr=False{numeric})")
        ts.append("}")
    py += [f"{name}.model_rebuild()" for name, definition in definitions.items() if definition.get("type") == "object"]
    artifacts = {Root / "shared/clinicalData.ts": "\n".join(ts) + "\n", Root / "backend/app/models/clinicalData.py": "\n".join(py) + "\n"}
    pins = {str(path.relative_to(Root)).replace("\\", "/"): hashlib.sha256(content.encode()).hexdigest() for path, content in artifacts.items()}
    artifacts[Root / "shared/schemaArtifacts.json"] = json.dumps({"schemaHash": digest, "artifacts": pins}, indent=2) + "\n"
    return artifacts


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    for path, content in generate().items():
        if options.check:
            if not path.is_file() or path.read_bytes() != content.encode("utf-8"):
                parser.exit(1, "Clinical schema representations are stale.\n")
        else:
            path.write_bytes(content.encode("utf-8"))
    print("Clinical schema representations synchronized.")


if __name__ == "__main__":
    main()
